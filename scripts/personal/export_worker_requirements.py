"""Write the hash-pinned requirements for the credential-free task-worker image.

The worker imports only the run contracts, so it needs just the packages below.
Versions and hashes come straight from the project's lockfile via ``uv export``;
nothing is resolved fresh. Usage:

    python scripts/personal/export_worker_requirements.py [--check]
"""

from __future__ import annotations

import re
import subprocess  # nosec B404 - fixed argv, no shell
import sys
from pathlib import Path

WORKER_PACKAGES = (
    "annotated-types",
    "pydantic",
    "pydantic-core",
    "pydantic-settings",
    "python-dotenv",
    "structlog",
    "typing-extensions",
    "typing-inspection",
)
OUTPUT = Path(__file__).resolve().parents[2] / "docker" / "task-worker.requirements.txt"
_HEADER = (
    "# Generated by scripts/personal/export_worker_requirements.py from uv.lock.\n"
    "# Do not edit by hand.\n"
)


def select_worker_requirements(exported: str) -> str:
    """Keep only the worker's packages from a ``uv export`` requirements text."""
    blocks = re.split(r"\n(?=[A-Za-z0-9_.-]+==)", exported)
    kept = [
        block.rstrip("\n")
        for block in blocks
        if block.split("==", 1)[0].strip() in WORKER_PACKAGES
    ]
    kept.sort(key=lambda block: block.split("==", 1)[0])
    return _HEADER + "\n".join(kept) + "\n"


def _export_from_lockfile() -> str:
    return subprocess.run(  # nosec B603
        [
            "uv",
            "export",
            "--frozen",
            "--no-emit-project",
            "--no-dev",
            "--format",
            "requirements-txt",
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def main(argv: list[str]) -> int:
    rendered = select_worker_requirements(_export_from_lockfile())
    if "--check" in argv:
        if OUTPUT.read_text() != rendered:
            sys.stderr.write("task-worker.requirements.txt is out of date\n")
            return 1
        return 0
    OUTPUT.write_text(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
