"""Write the hash-pinned requirements for the two small trusted images.

The credential-free task worker imports only the run contracts and the
conventions validator, so it needs just the worker packages (pydantic for the
contracts, tree-sitter for the validator). The Claude service image additionally
needs the MCP SDK and its dependencies for the worker-tools bridge.
Versions and hashes come straight from the project's lockfile via ``uv export``;
nothing is resolved fresh. Usage:

    python scripts/personal/export_worker_requirements.py [--check]
"""

from __future__ import annotations

import re
import subprocess  # nosec B404 - fixed argv, no shell
import sys
from pathlib import Path

WORKER_PACKAGES = (
    "annotated-types",
    "pydantic",
    "pydantic-core",
    "pydantic-settings",
    "python-dotenv",
    "pyyaml",
    "structlog",
    "tree-sitter",
    "tree-sitter-python",
    "tree-sitter-typescript",
    "typing-extensions",
    "typing-inspection",
)
# The MCP SDK's dependency closure (the stdio bridge is the only importer).
MCP_PACKAGES = (
    "anyio",
    "attrs",
    "cffi",
    "click",
    "cryptography",
    "h11",
    "httpcore2",
    "httpx2",
    "idna",
    "jsonschema",
    "jsonschema-specifications",
    "mcp",
    "mcp-types",
    "opentelemetry-api",
    "pycparser",
    "pyjwt",
    "python-multipart",
    "referencing",
    "rpds-py",
    "sse-starlette",
    "starlette",
    "truststore",
    "uvicorn",
)
SERVICE_PACKAGES = (*WORKER_PACKAGES, *MCP_PACKAGES)
_DOCKER_DIR = Path(__file__).resolve().parents[2] / "docker"
OUTPUT = _DOCKER_DIR / "task-worker.requirements.txt"
SERVICE_OUTPUT = _DOCKER_DIR / "claude-subscription.requirements.txt"
_HEADER = (
    "# Generated by scripts/personal/export_worker_requirements.py from uv.lock.\n"
    "# Do not edit by hand.\n"
)


def select_requirements(exported: str, packages: tuple[str, ...]) -> str:
    """Keep only the named packages from a ``uv export`` requirements text."""
    blocks = re.split(r"\n(?=[A-Za-z0-9_.-]+==)", exported)
    kept = [
        block.rstrip("\n")
        for block in blocks
        if block.split("==", 1)[0].strip() in packages
    ]
    kept.sort(key=lambda block: block.split("==", 1)[0])
    return _HEADER + "\n".join(kept) + "\n"


def select_worker_requirements(exported: str) -> str:
    return select_requirements(exported, WORKER_PACKAGES)


def _export_from_lockfile() -> str:
    return subprocess.run(  # nosec B603
        [
            "uv",
            "export",
            "--frozen",
            "--no-emit-project",
            "--no-dev",
            "--format",
            "requirements-txt",
        ],
        check=True,
        capture_output=True,
        text=True,
    ).stdout


def main(argv: list[str]) -> int:
    exported = _export_from_lockfile()
    targets = (
        (OUTPUT, select_requirements(exported, WORKER_PACKAGES)),
        (SERVICE_OUTPUT, select_requirements(exported, SERVICE_PACKAGES)),
    )
    if "--check" in argv:
        stale = [
            path.name for path, rendered in targets if path.read_text() != rendered
        ]
        for name in stale:
            sys.stderr.write(f"{name} is out of date\n")
        return 1 if stale else 0
    for path, rendered in targets:
        path.write_text(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
